package com.engboost.monitoringdevices.sample

import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.LinearGradient
import android.graphics.Paint
import android.graphics.Shader
import java.io.ByteArrayOutputStream
import java.nio.ByteBuffer
import java.nio.ByteOrder
import kotlin.math.PI
import kotlin.math.sin

/** TEMPORARY: generated PDF, PNG and WAV samples. Remove together with [SampleFilesSeeder]. */
internal object SampleMedia {

    fun pdf(): ByteArray {
        val document = android.graphics.pdf.PdfDocument()
        try {
            val titlePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply { textSize = 24f; isFakeBoldText = true }
            val textPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply { textSize = 12f; color = Color.DKGRAY }
            val boxPaint = Paint(Paint.ANTI_ALIAS_FLAG)

            repeat(2) { index ->
                // A4 in points.
                val page = document.startPage(android.graphics.pdf.PdfDocument.PageInfo.Builder(595, 842, index + 1).create())
                val canvas = page.canvas
                canvas.drawText("Sample PDF, page ${index + 1}", 56f, 90f, titlePaint)
                repeat(20) { line ->
                    canvas.drawText("Line ${line + 1}: generated by the app to try the PDF viewer.", 56f, 130f + line * 18f, textPaint)
                }
                listOf(0xFF4472C4.toInt(), 0xFFED7D31.toInt(), 0xFFA5A5A5.toInt()).forEachIndexed { bar, color ->
                    boxPaint.color = color
                    val height = 60f + bar * 40f + index * 30f
                    canvas.drawRect(56f + bar * 90f, 700f - height, 126f + bar * 90f, 700f, boxPaint)
                }
                document.finishPage(page)
            }
            return ByteArrayOutputStream().use { output ->
                document.writeTo(output)
                output.toByteArray()
            }
        } finally {
            document.close()
        }
    }

    /** Gradient picture with a big label, clearly a photo-like image and not a chart. */
    fun png(
        label: String = "Sample image",
        startColor: Int = 0xFF2F6FE4.toInt(),
        endColor: Int = 0xFF8E44D9.toInt(),
        width: Int = 1200,
        height: Int = 800
    ): ByteArray {
        val bitmap = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888)
        try {
            val canvas = Canvas(bitmap)
            val w = width.toFloat()
            val h = height.toFloat()
            val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                shader = LinearGradient(0f, 0f, w, h, startColor, endColor, Shader.TileMode.CLAMP)
            }
            canvas.drawRect(0f, 0f, w, h, paint)
            paint.shader = null

            // Sun and hills, so it reads as a picture at a glance.
            paint.color = 0x66FFFFFF
            canvas.drawCircle(w * 0.75f, h * 0.3f, h * 0.16f, paint)
            paint.color = 0x55000000
            canvas.drawPath(
                android.graphics.Path().apply {
                    moveTo(0f, h)
                    lineTo(w * 0.3f, h * 0.55f)
                    lineTo(w * 0.5f, h * 0.75f)
                    lineTo(w * 0.7f, h * 0.5f)
                    lineTo(w, h)
                    close()
                },
                paint
            )

            paint.color = Color.WHITE
            paint.textSize = h * 0.09f
            paint.isFakeBoldText = true
            canvas.drawText(label, w * 0.06f, h * 0.18f, paint)
            return ByteArrayOutputStream().use { output ->
                bitmap.compress(Bitmap.CompressFormat.PNG, 100, output)
                output.toByteArray()
            }
        } finally {
            bitmap.recycle()
        }
    }

    /** 16-bit mono PCM WAV: a short chord that fades out. */
    fun wav(seconds: Int = 4, sampleRate: Int = 22_050): ByteArray {
        val samples = seconds * sampleRate
        val pcm = ByteBuffer.allocate(samples * 2).order(ByteOrder.LITTLE_ENDIAN)
        val frequencies = listOf(261.63, 329.63, 392.0)
        for (index in 0 until samples) {
            val time = index.toDouble() / sampleRate
            val fade = 1.0 - index.toDouble() / samples
            val value = frequencies.sumOf { frequency -> sin(2 * PI * frequency * time) } / frequencies.size
            pcm.putShort((value * fade * 0.6 * Short.MAX_VALUE).toInt().toShort())
        }

        val dataSize = samples * 2
        val header = ByteBuffer.allocate(44).order(ByteOrder.LITTLE_ENDIAN).apply {
            put("RIFF".toByteArray()); putInt(36 + dataSize); put("WAVE".toByteArray())
            put("fmt ".toByteArray()); putInt(16); putShort(1); putShort(1)
            putInt(sampleRate); putInt(sampleRate * 2); putShort(2); putShort(16)
            put("data".toByteArray()); putInt(dataSize)
        }
        return header.array() + pcm.array()
    }
}
